/**
 * Matches every catalog species against ASPCA's toxic / non-toxic lists for cats and dogs
 * (data/aspca/plant-lists.json) and writes src/catalog/aspca.ts. The app uses these answers
 * first; plants ASPCA doesn't list keep their care group's answer, marked as inferred.
 *
 *   node scripts/build-aspca.js
 *
 * A species matches by its own name (or a cultivar's species), trying older names ASPCA still
 * uses, then by genus when ASPCA lists a whole genus ("Opuntia spp."). Conflicting entries
 * (both toxic and non-toxic) are left out.
 */
const fs = require('fs');
const path = require('path');

const lists = JSON.parse(
  fs.readFileSync(path.join(__dirname, '../data/aspca/plant-lists.json'), 'utf8'),
);
const csv = fs.readFileSync(
  path.join(__dirname, '../data/growspot/species-light-levels.csv'),
  'utf8',
);
const scientificNames = csv
  .split(/\r?\n/)
  .filter((l) => l && !l.startsWith('#'))
  .slice(1)
  .map((l) => {
    // common_name,scientific_name,light — the common name may be quoted.
    const m = l.match(/^(?:"(?:[^"]|"")*"|[^,]*),("(?:[^"]|"")*"|[^,]*),/);
    return m[1].replace(/^"|"$/g, '').replace(/""/g, '"').trim();
  });

// Older names ASPCA still uses for several genera.
const GENUS_SYNONYMS = {
  Goeppertia: ['Calathea'],
  Dracaena: ['Sansevieria'],
  Curio: ['Senecio'],
  Heptapleurum: ['Schefflera', 'Brassaia'],
  Thaumatophyllum: ['Philodendron'],
  Aloiampelos: ['Aloe'],
  Gonialoe: ['Aloe'],
  Aristaloe: ['Aloe'],
  Haworthiopsis: ['Haworthia'],
  Epipremnum: ['Scindapsus', 'Pothos'],
  Plerandra: ['Dizygotheca', 'Schefflera'],
  Callisia: ['Tradescantia', 'Setcreasea'],
  Coleus: ['Plectranthus', 'Solenostemon'],
  Selenicereus: ['Hylocereus'],
  Beaucarnea: ['Nolina'],
  Hatiora: ['Rhipsalidopsis'],
  Schlumbergera: ['Zygocactus'],
  Guarianthe: ['Cattleya'],
  Pericallis: ['Senecio'],
  Delairea: ['Senecio'],
  Chamaedorea: ['Collinia', 'Neanthe'],
  Dypsis: ['Chrysalidocarpus'],
};

const norm = (s) =>
  s
    .toLowerCase()
    .replace(/[×x]\s+/g, '')
    .replace(/['"‘’].*?['"‘’]/g, '')
    .replace(/\b(spp|sp|species|var|cv|subsp|hybrids?)\b\.?/g, ' ')
    .replace(/[^a-z ]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

function index(rows) {
  const species = new Map();
  const genus = new Map();
  for (const [, names, toxic] of rows) {
    for (const name of names) {
      const parts = norm(name).split(' ');
      if (!parts[0]) continue;
      const map = parts.length === 1 ? genus : species;
      const key = parts.length === 1 ? parts[0] : parts.slice(0, 2).join(' ');
      if (!map.has(key)) map.set(key, new Set());
      map.get(key).add(toxic);
    }
  }
  return { species, genus };
}

const verdict = (set) => (!set || set.size !== 1 ? null : [...set][0] ? 't' : 'n');

const idx = { cats: index(lists.cats), dogs: index(lists.dogs) };
const out = {};
for (const scientific of scientificNames) {
  const genusName = scientific.replace(/^[x×]\s+/i, '').split(/\s+/)[0];
  const [g, epithet] = norm(scientific).split(' ');
  const genera = [g, ...(GENUS_SYNONYMS[genusName] ?? []).map((x) => x.toLowerCase())];
  let code = '';
  for (const animal of ['cats', 'dogs']) {
    let v = null;
    if (epithet)
      for (const gn of genera)
        if ((v = verdict(idx[animal].species.get(`${gn} ${epithet}`)))) break;
    if (!v) for (const gn of genera) if ((v = verdict(idx[animal].genus.get(gn)))) break;
    code += v ?? '-';
  }
  if (code !== '--') out[scientific] = code;
}

fs.writeFileSync(
  path.join(__dirname, '../src/catalog/aspca.ts'),
  `// Generated by scripts/build-aspca.js — do not edit by hand.
// Pet safety per ASPCA's toxic and non-toxic plant lists (retrieved ${lists.retrieved}),
// matched to catalog species. Two letters, cats then dogs: t = toxic, n = non-toxic,
// - = not listed.

export const ASPCA_RETRIEVED = ${JSON.stringify(lists.retrieved)};

export const ASPCA: Record<string, string> = ${JSON.stringify(out, null, 1)};
`,
);
console.log(`${Object.keys(out).length} of ${scientificNames.length} species matched`);
