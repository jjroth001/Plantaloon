/**
 * Builds src/catalog/climate-data.ts: the average nightly low for each month on a 1° grid,
 * from NASA POWER's monthly climatology (2001–2025; power.larc.nasa.gov — NASA data, free to
 * use with credit). Nightly low ≈ mean temperature − half the mean daily range.
 *
 *   node scripts/build-climate.js <folder with raw/T2M_*.json and raw/T2M_RANGE_*.json>
 *
 * One byte per month and cell: °C + 100 (clamped), 255 = no data. 180 × 360 × 12 bytes,
 * stored base64.
 */
const fs = require('fs');
const path = require('path');

const source = process.argv[2];
if (!source) throw new Error('usage: node scripts/build-climate.js <download folder>');
const raw = path.join(source, 'raw');
const MONTHS = ['JAN', 'FEB', 'MAR', 'APR', 'MAY', 'JUN', 'JUL', 'AUG', 'SEP', 'OCT', 'NOV', 'DEC'];
const ROWS = 180;
const COLS = 360;

// Sum the native-resolution points (0.5° × 0.625°) into 1° cells.
const sums = new Float64Array(ROWS * COLS * 12);
const counts = new Uint32Array(ROWS * COLS);
const range = new Map();
for (const file of fs.readdirSync(raw).filter((f) => f.startsWith('T2M_RANGE_'))) {
  for (const [lat, lon, v] of JSON.parse(fs.readFileSync(path.join(raw, file), 'utf8'))) {
    range.set(`${lat},${lon}`, v);
  }
}
let points = 0;
for (const file of fs.readdirSync(raw).filter((f) => /^T2M_-?\d/.test(f))) {
  for (const [lat, lon, mean] of JSON.parse(fs.readFileSync(path.join(raw, file), 'utf8'))) {
    const r = range.get(`${lat},${lon}`);
    if (!mean || !r) continue;
    const row = Math.min(ROWS - 1, Math.max(0, Math.floor(lat + 90)));
    const col = ((Math.floor(lon + 180) % COLS) + COLS) % COLS;
    const cell = row * COLS + col;
    let ok = true;
    for (const m of MONTHS)
      if (mean[m] == null || mean[m] <= -999 || r[m] == null || r[m] <= -999) ok = false;
    if (!ok) continue;
    MONTHS.forEach((m, i) => (sums[cell * 12 + i] += mean[m] - r[m] / 2));
    counts[cell]++;
    points++;
  }
}

const bytes = new Uint8Array(ROWS * COLS * 12).fill(255);
let filled = 0;
for (let cell = 0; cell < ROWS * COLS; cell++) {
  if (!counts[cell]) continue;
  filled++;
  for (let i = 0; i < 12; i++) {
    const low = Math.round(sums[cell * 12 + i] / counts[cell]);
    bytes[cell * 12 + i] = Math.min(254, Math.max(0, low + 100));
  }
}

fs.writeFileSync(
  path.join(__dirname, '../src/catalog/climate-data.ts'),
  `// Generated by scripts/build-climate.js — do not edit by hand.
// Average nightly low per month on a 1° grid, from NASA POWER's 2001–2025 climatology
// (power.larc.nasa.gov). One byte per month and cell: °C + 100; 255 = no data.
export const CLIMATE = {
  rows: ${ROWS},
  cols: ${COLS},
  data: ${JSON.stringify(Buffer.from(bytes).toString('base64'))},
};
`,
);
console.log(`${points} points into ${filled} of ${ROWS * COLS} cells`);
