/**
 * Bundles the catalog photos: copies the shrunk WebP thumbnails into assets/catalog-photos/
 * and writes src/catalog/photos.ts with each photo's author, licence and Commons page.
 *
 *   node scripts/build-photos.js <folder with meta.json and out/>
 *
 * The folder comes from a one-time download of each species' Wikidata image (P18) from
 * Wikimedia Commons, shrunk to 400×400 WebP. Only freely licensed photos (public domain,
 * CC0, CC BY, CC BY-SA, GFDL) are included; each is credited in the app.
 */
const fs = require('fs');
const path = require('path');

const source = process.argv[2];
if (!source) throw new Error('usage: node scripts/build-photos.js <download folder>');
const meta = JSON.parse(fs.readFileSync(path.join(source, 'meta.json'), 'utf8'));
const assets = path.join(__dirname, '../assets/catalog-photos');
fs.rmSync(assets, { recursive: true, force: true });
fs.mkdirSync(assets, { recursive: true });

const slug = (s) =>
  s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const entries = [];
let bytes = 0;
for (const [species, m] of Object.entries(meta).sort(([a], [b]) => a.localeCompare(b))) {
  if (!m.file) continue;
  const from = path.join(source, 'out', m.file);
  if (!fs.existsSync(from)) continue;
  const id = slug(species);
  fs.copyFileSync(from, path.join(assets, `${id}.webp`));
  bytes += fs.statSync(from).size;
  const author = m.author.replace(/\s+/g, ' ').trim() || 'Unknown';
  entries.push(
    `  ${JSON.stringify(id)}: [require('../../assets/catalog-photos/${id}.webp'), ${JSON.stringify(author)}, ${JSON.stringify(m.licence)}, ${JSON.stringify(m.page)}],`,
  );
}

fs.writeFileSync(
  path.join(__dirname, '../src/catalog/photos.ts'),
  `// Generated by scripts/build-photos.js — do not edit by hand.
// Photos from Wikimedia Commons (via each species' Wikidata image), shrunk to 400×400.
// Each entry: [image, author, licence, Commons page]. Keyed by species id (cultivars use
// their species' photo).
/* eslint-disable */

export const CATALOG_PHOTOS: Record<string, readonly [number, string, string, string]> = {
${entries.join('\n')}
};
`,
);
console.log(`${entries.length} photos, ${(bytes / 1e6).toFixed(1)} MB`);
