/**
 * Turns data/growspot/species-light-levels.csv (GrowSpot, CC BY 4.0) into
 * src/catalog/growspot-species.ts, a compact table the app bundles.
 *
 *   node scripts/build-species.js
 */
const fs = require('fs');
const path = require('path');

const source = path.join(__dirname, '../data/growspot/species-light-levels.csv');
const lines = fs.readFileSync(source, 'utf8').split(/\r?\n/);
const attribution = lines.find((l) => l.startsWith('#')).replace(/^#\s*/, '');

// Minimal CSV parsing: fields may be quoted and contain commas.
function parse(line) {
  const out = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (quoted) {
      if (c === '"' && line[i + 1] === '"') ((field += '"'), i++);
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') (out.push(field), (field = ''));
    else field += c;
  }
  out.push(field);
  return out;
}

const rows = lines.filter((l) => l && !l.startsWith('#')).map(parse);
const [header, ...data] = rows;
if (header.join() !== 'common_name,scientific_name,light_requirement') {
  throw new Error(`unexpected columns: ${header}`);
}
const tiers = new Set(['low', 'medium', 'high', 'very_high']);
const table = data.map(([common, scientific, tier]) => {
  if (!tiers.has(tier)) throw new Error(`unknown tier ${tier} for ${scientific}`);
  return [scientific.trim(), common.trim(), tier];
});

fs.writeFileSync(
  path.join(__dirname, '../src/catalog/growspot-species.ts'),
  `// Generated by scripts/build-species.js — do not edit by hand.
// ${attribution}
// Columns: scientific name, common name(s) (" / " separates alternatives), light tier.

import type { LightTier } from './types';

export const GROWSPOT_ATTRIBUTION = ${JSON.stringify(attribution)};

export const GROWSPOT_SPECIES: readonly (readonly [string, string, LightTier])[] = ${JSON.stringify(
    table,
  )
    .replace(/\],\[/g, '],\n  [')
    .replace(/^\[\[/, '[\n  [')
    .replace(/\]\]$/, '],\n]')};
`,
);
console.log(`wrote ${table.length} species`);
